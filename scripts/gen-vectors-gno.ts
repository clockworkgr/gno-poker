// Turns vectors/vectors.json (written by the TypeScript implementation, `pnpm vectors`) into
// contracts/gno.land/p/demo/poker/cards/vectors_gen_test.gno, a gno test asserting that the gno
// implementation reproduces every value. Run: node scripts/gen-vectors-gno.ts

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "vectors/vectors.json");
const out = join(root, "contracts/gno.land/p/demo/poker/cards/vectors_gen_test.gno");

interface SeedVectors {
  seed: string;
  commit: string;
  shuffleKey: string;
  cardKey0: string;
  cardKey51: string;
  permutation: number[];
}
interface Vectors {
  P: string;
  CANON_ROOT: string;
  m0: string;
  m51: string;
  shufflePassCanonicalA: { root: string; proofIndex7: string; element7: string; first: string; last: string };
  [k: string]: unknown;
}

const v = JSON.parse(readFileSync(src, "utf8")) as Vectors;
const hex = (s: unknown, what: string): string => {
  if (typeof s !== "string" || !/^[0-9a-f]*$/.test(s)) throw new Error(`${what}: expected lowercase hex`);
  return JSON.stringify(s);
};

const seeds = Object.entries(v)
  .filter(([k, x]) => /^seed[A-Z]$/.test(k) && typeof x === "object" && x !== null)
  .map(([k, x]) => [k, x as SeedVectors] as const);
if (!seeds.some(([k]) => k === "seedA")) throw new Error("vectors.json has no seedA");

const lines: string[] = [];
lines.push(`// Code generated by scripts/gen-vectors-gno.ts from vectors/vectors.json. DO NOT EDIT.`);
lines.push(``);
lines.push(`package cards`);
lines.push(``);
lines.push(`import (`);
lines.push(`\t"crypto/modexp"`);
lines.push(`\t"testing"`);
lines.push(`)`);
lines.push(``);
lines.push(`func genExpectHex(t *testing.T, what string, got []byte, want string) {`);
lines.push(`\tt.Helper()`);
lines.push(`\tif EncodeHex(got) != want {`);
lines.push(`\t\tt.Errorf("%s: got %s, want %s", what, EncodeHex(got), want)`);
lines.push(`\t}`);
lines.push(`}`);
lines.push(``);
lines.push(`func genSeed(t *testing.T, h string) []byte {`);
lines.push(`\tb, err := DecodeHex(h, 32)`);
lines.push(`\tif err != nil {`);
lines.push(`\t\tt.Fatal(err)`);
lines.push(`\t}`);
lines.push(`\treturn b`);
lines.push(`}`);
lines.push(``);
lines.push(`func TestGeneratedVectorsGroup(t *testing.T) {`);
lines.push(`\tgenExpectHex(t, "P", P(), ${hex(v.P, "P")})`);
lines.push(`\tgenExpectHex(t, "CanonRoot()", CanonRoot(), ${hex(v.CANON_ROOT, "CANON_ROOT")})`);
lines.push(`\tdeck := canonicalDeck()`);
lines.push(`\tgenExpectHex(t, "MerkleRoot(canonical deck)", MerkleRoot(deck), ${hex(v.CANON_ROOT, "CANON_ROOT")})`);
lines.push(`\tgenExpectHex(t, "m0", deck[:CardLen], ${hex(v.m0, "m0")})`);
lines.push(`\tgenExpectHex(t, "m51", deck[51*CardLen:], ${hex(v.m51, "m51")})`);
lines.push(`}`);
for (const [name, s] of seeds) {
  if (!Array.isArray(s.permutation) || s.permutation.length !== 52) throw new Error(`${name}.permutation must have 52 entries`);
  lines.push(``);
  lines.push(`func TestGeneratedVectors_${name}(t *testing.T) {`);
  lines.push(`\tseed := genSeed(t, ${hex(s.seed, `${name}.seed`)})`);
  lines.push(`\tgenExpectHex(t, "${name}.commit", Commit(seed), ${hex(s.commit, `${name}.commit`)})`);
  lines.push(`\tgenExpectHex(t, "${name}.shuffleKey", ShuffleKey(seed), ${hex(s.shuffleKey, `${name}.shuffleKey`)})`);
  lines.push(`\tgenExpectHex(t, "${name}.cardKey0", CardKey(seed, 0), ${hex(s.cardKey0, `${name}.cardKey0`)})`);
  lines.push(`\tgenExpectHex(t, "${name}.cardKey51", CardKey(seed, 51), ${hex(s.cardKey51, `${name}.cardKey51`)})`);
  lines.push(`\twant := []int{${s.permutation.map((x) => String(Number(x))).join(", ")}}`);
  lines.push(`\tgot := Permutation(seed)`);
  lines.push(`\tif len(got) != len(want) {`);
  lines.push(`\t\tt.Fatalf("${name}.permutation: length %d", len(got))`);
  lines.push(`\t}`);
  lines.push(`\tfor i := range want {`);
  lines.push(`\t\tif got[i] != want[i] {`);
  lines.push(`\t\t\tt.Fatalf("${name}.permutation[%d]: got %d, want %d", i, got[i], want[i])`);
  lines.push(`\t\t}`);
  lines.push(`\t}`);
  lines.push(`}`);
}
const sp = v.shufflePassCanonicalA;
lines.push(``);
lines.push(`// D[i] = canonical[perm(seedA)[i]] ^ shuffleKey(seedA) mod P (protocol section 4.1).`);
lines.push(`func TestGeneratedVectorsShufflePassA(t *testing.T) {`);
lines.push(`\tseed := genSeed(t, ${hex((v.seedA as SeedVectors).seed, "seedA.seed")})`);
lines.push(`\tcanon := canonicalDeck()`);
lines.push(`\tperm := Permutation(seed)`);
lines.push(`\te := ShuffleKey(seed)`);
lines.push(`\tp := P()`);
lines.push(`\tdeck := make([]byte, 0, DeckLen)`);
lines.push(`\tfor i := 0; i < DeckSize; i++ {`);
lines.push(`\t\tsrc := canon[perm[i]*CardLen : (perm[i]+1)*CardLen]`);
lines.push(`\t\tdeck = append(deck, modexp.ModExp(src, e, p)...)`);
lines.push(`\t}`);
lines.push(`\tgenExpectHex(t, "shufflePassCanonicalA.root", MerkleRoot(deck), ${hex(sp.root, "root")})`);
lines.push(`\tgenExpectHex(t, "shufflePassCanonicalA.first", deck[:CardLen], ${hex(sp.first, "first")})`);
lines.push(`\tgenExpectHex(t, "shufflePassCanonicalA.last", deck[51*CardLen:], ${hex(sp.last, "last")})`);
lines.push(`\tgenExpectHex(t, "shufflePassCanonicalA.element7", deck[7*CardLen:8*CardLen], ${hex(sp.element7, "element7")})`);
lines.push(`\tgenExpectHex(t, "shufflePassCanonicalA.proofIndex7", MerkleProof(deck, 7), ${hex(sp.proofIndex7, "proofIndex7")})`);
lines.push(`\tif !VerifyProof(MerkleRoot(deck), deck[7*CardLen:8*CardLen], 7, MerkleProof(deck, 7)) {`);
lines.push(`\t\tt.Fatal("proof for index 7 does not verify")`);
lines.push(`\t}`);
lines.push(`\tif _, root, err := ParseDeck(EncodeDeck(deck)); err != nil || EncodeHex(root) != ${hex(sp.root, "root")} {`);
lines.push(`\t\tt.Fatalf("ParseDeck: %v", err)`);
lines.push(`\t}`);
lines.push(`}`);
lines.push(``);

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${seeds.length} seeds)`);
